"""Write the x64glibc CRT objects and link stubs from scripts/linux-stubs/.

Run from the repository root:
  python3 scripts/make_linux_stubs.py           writes the objects and stubs
  python3 scripts/make_linux_stubs.py --audit   lists archive references the catalog lacks
  python3 scripts/make_linux_stubs.py --audit <archive>...   also audits these archives

Writing needs the pinned Zig. The audit needs only nm.
scripts/linux-stubs/README.md says what a stub holds and how to change the
catalog, scripts/linux-stubs/stubs.json.
"""

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "scripts/linux-stubs"
CATALOG = SOURCES / "stubs.json"
CRT_OBJECTS = ("Scrt1", "crti", "crtn")
OUTPUT = ROOT / "platform/targets/x64glibc"
AUDITED = ("libhost.a", "sokol_app.a", "sokol_gfx.a", "sokol_glue.a", "sokol_log.a", "clay.a")
# Another Zig can write other bytes, and CI fails on any diff.
ZIG_VERSION = "0.16.0"
TARGET = "x86_64-linux-gnu"
ZIG_FLAGS = ["-target", TARGET, "-g0"]
SONAME = re.compile(r"lib[A-Za-z0-9_+-]+\.so\.[0-9]+")
# A stub has no symbol versions, so a name never carries an @VERSION suffix.
SYMBOL = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
# The Roc app defines roc_ names. lld relaxes the host's TLS calls to
# __tls_get_addr away, so no stub needs it.
AUDIT_SKIPS = ("roc_", "__tls_get_addr")


def names(library):
    return library["functions"] + [record["name"] for record in library.get("objects", [])]


def validate(catalog):
    if set(catalog) != {"schema_version", "target", "libraries"}:
        raise ValueError("the catalog needs schema_version, target and libraries, and nothing else")
    if catalog["schema_version"] != 1 or catalog["target"] != TARGET:
        raise ValueError(f"the catalog must be schema_version 1 for {TARGET}")
    sonames, seen = set(), set()
    for library in catalog["libraries"]:
        if not {"soname", "functions"} <= set(library) <= {"soname", "functions", "objects"}:
            raise ValueError(f"{library.get('soname')}: a library has a soname, functions and optional objects")
        soname = library["soname"]
        if not SONAME.fullmatch(soname):
            raise ValueError(f"{soname}: a soname is lib<name>.so.<version>")
        if soname in sonames:
            raise ValueError(f"{soname}: listed twice")
        sonames.add(soname)
        for record in library.get("objects", []):
            if not isinstance(record, dict) or set(record) != {"name", "size"}:
                raise ValueError(f"{record}: an object is a name and a size")
            if type(record["size"]) is not int or record["size"] <= 0:
                raise ValueError(f"{record['name']}: the size must be a positive number of bytes")
        for name in names(library):
            if not SYMBOL.fullmatch(name):
                raise ValueError(f"{name}: not a C identifier")
            if name in seen:
                raise ValueError(f"{name}: listed twice")
            seen.add(name)
    return catalog


def render(catalog):
    files = {}
    for library in catalog["libraries"]:
        lines = [
            "# Generated by scripts/make_linux_stubs.py. The linker reads it, the program never runs it.",
            ".text",
            "",
        ]
        for name in sorted(library["functions"]):
            lines += [f".globl {name}", f".type {name}, @function", f"{name}:", "\tret", ""]
        # The executable copies an object into its own .bss, so the size must match the library's.
        objects = sorted(library.get("objects", []), key=lambda record: record["name"])
        if objects:
            lines += [".data", ""]
        for record in objects:
            name, size = record["name"], record["size"]
            lines += [f".globl {name}", f".type {name}, @object", f".size {name}, {size}", f"{name}:", f"\t.zero {size}", ""]
        lines.append('.section .note.GNU-stack,"",@progbits')
        files[library["soname"]] = "\n".join(lines) + "\n"
    return files


def check_zig():
    try:
        found = subprocess.run(["zig", "version"], capture_output=True, text=True, check=True).stdout.strip()
    except FileNotFoundError:
        sys.exit(f"zig is not on PATH. Install Zig {ZIG_VERSION}.")
    if found != ZIG_VERSION:
        sys.exit(f"zig is {found}. Use Zig {ZIG_VERSION}, so the outputs match the committed files.")


def zig(args, cwd):
    subprocess.run(["zig", "cc", *ZIG_FLAGS, *args], cwd=cwd, check=True)


# Zig runs in a temporary directory on bare file names, so no path reaches the outputs.
# A stub that left the catalog is deleted, so the committed files follow the catalog.
def build(assembly, out):
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.so.*"):
        if old.name not in assembly:
            old.unlink()
    with tempfile.TemporaryDirectory() as tmp:
        for name in CRT_OBJECTS:
            source = f"{name}.s"
            (Path(tmp) / source).write_text((SOURCES / source).read_text())
            zig(["-c", source, "-o", str(out / f"{name}.o")], tmp)
        for soname, text in assembly.items():
            source = f"{soname}.s"
            (Path(tmp) / source).write_text(text)
            zig(["-shared", "-nostdlib", "-s", f"-Wl,-soname,{soname}", source, "-o", str(out / soname)], tmp)


# Reads `nm -g -P`, which GNU nm and llvm-nm print alike. Weak undefined
# names (w, v) may stay unresolved, so they are not references.
def parse_nm(text):
    undefined, defined = [], []
    for line in text.splitlines():
        fields = line.split()
        if len(fields) < 2 or line.endswith(":"):
            continue
        name, kind = fields[0], fields[1]
        if kind == "U":
            undefined.append(name)
        elif kind not in ("w", "v"):
            defined.append(name)
    return undefined, defined


# Odin names package symbols package::name, so no stub defines one.
def uncovered(catalog, undefined, defined):
    known = {name for library in catalog["libraries"] for name in names(library)}
    skip = known | set(defined)
    return sorted(
        {name for name in undefined if name not in skip and not name.startswith(AUDIT_SKIPS) and "::" not in name}
    )


def audit(catalog, extra):
    undefined, defined = [], []
    for path in [OUTPUT / name for name in AUDITED] + extra:
        out = subprocess.run(["nm", "-g", "-P", str(path)], capture_output=True, text=True, check=True)
        archive_undefined, archive_defined = parse_nm(out.stdout)
        undefined += archive_undefined
        defined += archive_defined
    return uncovered(catalog, undefined, defined)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--audit",
        nargs="*",
        type=Path,
        metavar="ARCHIVE",
        help=f"list references in {OUTPUT} and in each ARCHIVE that the catalog lacks",
    )
    args = parser.parse_args()
    catalog = validate(json.loads(CATALOG.read_text()))
    if args.audit is not None:
        missing = audit(catalog, args.audit)
        for name in missing:
            print(name)
        sys.exit(1 if missing else 0)
    check_zig()
    build(render(catalog), OUTPUT)
    count = sum(len(names(library)) for library in catalog["libraries"])
    print(f"{OUTPUT.relative_to(ROOT)}: {len(CRT_OBJECTS)} CRT objects, {len(catalog['libraries'])} stubs, {count} symbols")


if __name__ == "__main__":
    main()
