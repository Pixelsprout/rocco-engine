# Run from the repository root: python3 -m unittest scripts/test_make_linux_stubs.py

import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import make_linux_stubs as stubs


def catalog():
    return {
        "schema_version": 1,
        "target": "x86_64-linux-gnu",
        "libraries": [
            {"soname": "libc.so.6", "functions": ["malloc", "free"], "objects": [{"name": "stderr", "size": 8}]},
            {"soname": "libX11.so.6", "functions": ["XOpenDisplay"]},
        ],
    }


class RenderTest(unittest.TestCase):
    def test_writes_one_sorted_assembly_stub_per_soname(self):
        files = stubs.render(stubs.validate(catalog()))
        self.assertEqual(sorted(files), ["libX11.so.6", "libc.so.6"])
        self.assertEqual(
            files["libc.so.6"],
            "# Generated by scripts/make_linux_stubs.py. The linker reads it, the program never runs it.\n"
            ".text\n"
            "\n"
            ".globl free\n"
            ".type free, @function\n"
            "free:\n"
            "\tret\n"
            "\n"
            ".globl malloc\n"
            ".type malloc, @function\n"
            "malloc:\n"
            "\tret\n"
            "\n"
            ".data\n"
            "\n"
            ".globl stderr\n"
            ".type stderr, @object\n"
            ".size stderr, 8\n"
            "stderr:\n"
            "\t.zero 8\n"
            "\n"
            '.section .note.GNU-stack,"",@progbits\n',
        )

    def test_a_library_with_no_objects_has_no_data_section(self):
        files = stubs.render(stubs.validate(catalog()))
        self.assertNotIn(".data", files["libX11.so.6"])


class ValidateTest(unittest.TestCase):
    def rejects(self, change):
        bad = catalog()
        change(bad)
        with self.assertRaises(ValueError):
            stubs.validate(bad)

    def test_accepts_the_example(self):
        stubs.validate(catalog())

    def test_rejects_another_target(self):
        self.rejects(lambda c: c.update(target="aarch64-linux-gnu"))

    def test_rejects_an_unknown_library_key(self):
        self.rejects(lambda c: c["libraries"][0].update(versions=["GLIBC_2.2.5"]))

    def test_rejects_a_soname_with_no_version(self):
        self.rejects(lambda c: c["libraries"][0].update(soname="libc.so"))

    def test_rejects_a_soname_with_a_path(self):
        self.rejects(lambda c: c["libraries"][0].update(soname="../libc.so.6"))

    def test_rejects_a_soname_twice(self):
        self.rejects(lambda c: c["libraries"][1].update(soname="libc.so.6"))

    def test_rejects_a_function_twice(self):
        self.rejects(lambda c: c["libraries"][1]["functions"].append("malloc"))

    def test_rejects_an_object_with_no_size(self):
        self.rejects(lambda c: c["libraries"][0]["objects"][0].update(size=0))

    def test_rejects_an_object_with_the_name_of_a_function(self):
        self.rejects(lambda c: c["libraries"][1].update(objects=[{"name": "malloc", "size": 8}]))

    def test_rejects_a_name_that_is_not_a_c_identifier(self):
        self.rejects(lambda c: c["libraries"][0]["functions"].append("memcpy@GLIBC_2.14"))


class AuditTest(unittest.TestCase):
    def test_reads_undefined_and_defined_names_from_posix_nm_output(self):
        text = (
            "libhost.a[engine.o]:\n"
            "malloc U\n"
            "__gmon_start__ w\n"
            "engine_step T 0000000000000010 0000000000000020\n"
            "g_state B 0000000000000000 0000000000000008\n"
            "roc__main_for_host_1_exposed U\n"
        )
        self.assertEqual(
            stubs.parse_nm(text),
            (["malloc", "roc__main_for_host_1_exposed"], ["engine_step", "g_state"]),
        )

    def test_lists_references_that_no_archive_defines_and_the_catalog_lacks(self):
        undefined = ["malloc", "stderr", "calloc", "XOpenDisplay", "clay_layout", "roc_alloc", "__tls_get_addr"]
        defined = ["clay_layout"]
        self.assertEqual(stubs.uncovered(stubs.validate(catalog()), undefined, defined), ["calloc"])

    def test_skips_odin_package_symbols(self):
        undefined = ["os::is_tty", "log::[file_console_logger.odin]::global_subtract_stderr_options", "calloc"]
        self.assertEqual(stubs.uncovered(stubs.validate(catalog()), undefined, []), ["calloc"])


if __name__ == "__main__":
    unittest.main()
